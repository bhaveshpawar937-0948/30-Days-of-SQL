-- ------------------------------------------------------------
-- 1. View available databases
-- ------------------------------------------------------------

SHOW DATABASES;


-- ------------------------------------------------------------
-- 2. Create a new database
-- ------------------------------------------------------------

CREATE DATABASE sql_30_days;


-- ------------------------------------------------------------
-- 3. Select the database
-- ------------------------------------------------------------

USE sql_30_days;


-- ------------------------------------------------------------
-- 4. Create a students table
-- ------------------------------------------------------------

CREATE TABLE students (
    student_id INT PRIMARY KEY,
    name VARCHAR(100),
    age INT,
    department VARCHAR(100),
    city VARCHAR(100)
);


-- ------------------------------------------------------------
-- 5. Display all tables in the current database
-- ------------------------------------------------------------

SHOW TABLES;


-- ------------------------------------------------------------
-- 6. View the structure of the students table
-- ------------------------------------------------------------

DESCRIBE students;


-- ------------------------------------------------------------
-- 7. Create another table
-- ------------------------------------------------------------

CREATE TABLE courses (
    course_id INT PRIMARY KEY,
    course_name VARCHAR(100),
    duration_months INT
);


-- ------------------------------------------------------------
-- 8. View the courses table structure
-- ------------------------------------------------------------

DESCRIBE courses;


-- ------------------------------------------------------------
-- 9. Display all tables again
-- ------------------------------------------------------------

SHOW TABLES;
